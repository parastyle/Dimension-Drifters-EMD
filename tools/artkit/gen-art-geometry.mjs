#!/usr/bin/env node
// Generate presentation-only weapon geometry from the committed orientation audit. Raw PCA is never
// trusted for the report's manual-review outliers: their business axes were reviewed separately and are
// encoded below. Tome open-state angle/size measurements are safe because every open spread is directional.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(here, "../..");
const REPORT_PATH = resolve(here, "out/orientation/weapon-axis-report.json");
const OUTPUT_PATH = resolve(REPO, "packages/client/src/sprites/art-geometry.generated.ts");

const report = JSON.parse(readFileSync(REPORT_PATH, "utf8"));

/**
 * Reviewed business-axis corrections for every raw >22.5 degree PCA outlier. Six are L-shaped guns whose
 * barrels visibly point image-right; the remainder are books/props with no trustworthy silhouette axis.
 * Zero is therefore an intentional correction, not a missing measurement.
 */
const REVIEWED_OUTLIER_ART_ANGLE = Object.freeze({
  "x2-ashfall-peacemaker": 0,
  "x2-emberleaf-chapbook": 0,
  "x2-fool-s-gold-revolver": 0,
  "x2-grit-snubnose": 0,
  "x2-hexbloom-scattergrimoire": 0,
  "x2-hollowpoint-hex": 0,
  "x2-idol-of-the-pale-verdict": 0,
  "x2-ironhail-pepperbox": 0,
  "x2-riftglass-prism-lantern": 0,
  "x2-tumbleweed-skipper": 0,
});

const OPEN_TOME_ORIGIN_X = 0.5;
const OPEN_TOME_ORIGIN_Y = 0.85;
const VERDIGRIS_TARGET_DISPLAY_LENGTH = 94;

const round = (value) => Math.round(value * 1_000_000_000) / 1_000_000_000;
const radians = (degrees) => round((degrees * Math.PI) / 180);

const outliers = report.weapons.filter(
  (weapon) => Math.abs(weapon.deviationFromRigAssumedPositiveXDeg) > 22.5,
);
const outlierIds = outliers.map((weapon) => weapon.id).sort();
const reviewedIds = Object.keys(REVIEWED_OUTLIER_ART_ANGLE).sort();
if (JSON.stringify(outlierIds) !== JSON.stringify(reviewedIds)) {
  throw new Error(
    `Reviewed outlier list is stale. Report=${outlierIds.join(",")} reviewed=${reviewedIds.join(",")}`,
  );
}
if (outliers.some((weapon) => weapon.correctionDisposition.startsWith("pca-correction"))) {
  throw new Error("A raw orientation outlier unexpectedly became safe for automatic PCA correction");
}

const weaponById = new Map(report.weapons.map((weapon) => [weapon.id, weapon]));
const tomeSizeById = new Map(report.tomeSize.map((tome) => [tome.id, tome]));
const geometry = new Map();

for (const id of outlierIds) {
  geometry.set(id, {
    closed: { artAngle: REVIEWED_OUTLIER_ART_ANGLE[id] },
  });
}

for (const open of report.tomeOpen) {
  const weapon = weaponById.get(open.id);
  const size = tomeSizeById.get(open.id);
  if (!weapon || !size) throw new Error(`Incomplete tome geometry report for ${open.id}`);
  if (Math.abs(open.deviationFromRigAssumedPositiveXDeg) > 22.5) {
    throw new Error(`Open tome ${open.id} no longer has a trustworthy horizontal axis`);
  }
  const closedDisplayLengthMul =
    open.id === "x2-verdigris-grand-grimoire"
      ? VERDIGRIS_TARGET_DISPLAY_LENGTH / size.displayLengthPx
      : 1;
  const visibleAreaRatio = size.openToClosedRatio.alphaEquivalentArea;
  if (!(visibleAreaRatio > 0)) throw new Error(`Invalid open/closed area ratio for ${open.id}`);

  geometry.set(open.id, {
    closed: {
      artAngle: REVIEWED_OUTLIER_ART_ANGLE[open.id] ?? 0,
      originX: weapon.manifest.effectiveRuntimeOriginX,
      originY: 0.5,
      displayLengthMul: round(closedDisplayLengthMul),
    },
    open: {
      artAngle: radians(open.measuredAngleDeg),
      originX: OPEN_TOME_ORIGIN_X,
      originY: OPEN_TOME_ORIGIN_Y,
      // Equalize painted alpha area rather than forcing an open spread into the closed canvas width.
      displayLengthMul: round(closedDisplayLengthMul / Math.sqrt(visibleAreaRatio)),
    },
  });
}

const lines = [
  "// Generated by tools/artkit/gen-art-geometry.mjs from the committed orientation report.",
  "// Do not hand-edit; reviewed unsafe-PCA overrides live in the generator.",
  "",
  "export interface WeaponArtStateGeometry {",
  "  readonly artAngle: number;",
  "  readonly originX?: number;",
  "  readonly originY?: number;",
  "  readonly displayLengthMul?: number;",
  "}",
  "",
  "export interface WeaponArtGeometry {",
  "  readonly closed: WeaponArtStateGeometry;",
  "  readonly open?: WeaponArtStateGeometry;",
  "}",
  "",
  `export const REVIEWED_ART_AXIS_OUTLIER_IDS = ${JSON.stringify(outlierIds, null, 2)} as const;`,
  "",
  "export const WEAPON_ART_GEOMETRY = {",
];

for (const [id, states] of [...geometry].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(states, null, 2).replace(/^/gm, "  ").trimStart()},`);
}

lines.push(
  "} as const satisfies Readonly<Record<string, WeaponArtGeometry>>;",
  "",
  "export function weaponArtGeometryFor(spriteId: string): WeaponArtGeometry | undefined {",
  "  return (WEAPON_ART_GEOMETRY as Readonly<Record<string, WeaponArtGeometry>>)[spriteId];",
  "}",
  "",
);

writeFileSync(OUTPUT_PATH, `${lines.join("\n")}\n`, "utf8");
console.log(`Generated ${OUTPUT_PATH} (${geometry.size} sprites)`);
