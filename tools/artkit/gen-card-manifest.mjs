#!/usr/bin/env node
// Regenerates packages/client/src/sprites/card-manifest.ts from the card PNGs that
// actually exist under packages/client/public/cards/. The Arena preload loads card art
// ONLY for ids in this manifest, so weapons without bespoke card art fall back to the
// sprite/icon card cleanly — no 404 flood masking real errors (§28.5 two-pass art).
//
// Run after card art lands (harvest-install / manual drop): `node tools/artkit/gen-card-manifest.mjs`.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cardsDir = resolve(here, "../../packages/client/public/cards");
const outFile = resolve(here, "../../packages/client/src/sprites/card-manifest.ts");

let ids = [];
try {
  ids = readdirSync(cardsDir)
    .filter((f) => f.toLowerCase().endsWith(".jpg"))
    .map((f) => f.replace(/\.jpg$/i, ""))
    .sort();
} catch {
  // No cards dir yet — emit an empty manifest so the import always resolves.
}

const body = `// AUTO-GENERATED by tools/artkit/gen-card-manifest.mjs — do not edit by hand.
// Weapon ids that have bespoke card art under public/cards/<id>.jpg. The §9 carousel
// preloads card art only for these (others use the sprite/icon fallback, §28.5).

export const CARD_ART_IDS = [
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
] as const;
`;

writeFileSync(outFile, body, "utf8");
console.log(`card-manifest: ${ids.length} card(s) -> ${outFile}`);
