#!/usr/bin/env node
// artkit/gen-dimensions.mjs — codegen the §17 themed DIMENSIONS (Frostfell, Verdant Ruins, Ashlands,
// Neon-Cyber) + their all-tier enemy rosters + the 3 cross-dimensional SHIFTERS into one typed module the
// game merges into DIMENSIONS and ENEMY_KINDS. Sources:
//   data/dimensions-design.json   — 4 dims, each {palette, hazard, 4 enemies, 1 tough, 1 boss}
//   data/dimension-shifters.json  — 3 roaming-invader shifters (global, spawned by the shifter director)
// Wild West (dimension 1) stays hand-authored in shared/dimensions.ts + shared/enemies.ts.
//
//   node tools/artkit/gen-dimensions.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)));
const REPO = resolve(ROOT, "..", "..");
const DIMS_SRC = join(REPO, "data", "dimensions-design.json");
const SHIFT_SRC = join(REPO, "data", "dimension-shifters.json");
const OUT = join(REPO, "packages", "shared", "src", "dimensions.generated.ts");

const num = (v, d) => (Number.isFinite(Number(v)) ? Number(v) : d);

/** Normalize a "#rrggbb" or "0xrrggbb" colour to the sentinel string "0xrrggbb" (lowercased). The final
 *  serialization unquotes these into real hex-number literals (regex below) so the palette stays readable. */
function color(c) {
  const hex = String(c)
    .trim()
    .replace(/^#/, "")
    .replace(/^0x/i, "")
    .toLowerCase()
    .padStart(6, "0")
    .slice(0, 6);
  return `0x${hex}`;
}

function palette(p) {
  return {
    groundBed: color(p.groundBed),
    gridColor1: color(p.gridColor1),
    gridColor2: color(p.gridColor2),
    boundaryRail: color(p.boundaryRail),
    pitVoid: color(p.pitVoid),
    pitRustBand: color(p.pitRustBand),
    pitAmberLip: color(p.pitAmberLip),
    spawnRingSafe: color(p.spawnRingSafe),
    dustDrift: color(p.dustDrift),
  };
}

/** Map a design enemy/tough/boss/shifter record → a clean EnemyKind object (only the EnemyKind fields; the
 *  art-only fields name/artPrompt/palettePrimary are dropped). Field order mirrors the interface. */
function mapKind(e, { boss = false, shifter = false } = {}) {
  const k = {
    sprite: e.id,
    archetype: e.archetype,
  };
  if (e.renderScale) k.renderScale = num(e.renderScale, 1);
  k.speed = num(e.speed, 120);
  k.hp = num(e.hp, 5);
  k.radius = num(e.radius, shifter ? Math.round(22 * num(e.renderScale, 1)) : 20);
  k.contactDamage = num(e.contactDamage, 0);
  k.weight = num(e.weight, boss ? 0 : 1);
  k.xpValue = num(e.xpValue, boss ? 40 : 1);
  if (e.ranged) {
    const r = e.ranged;
    k.ranged = {
      range: num(r.range, 560),
      preferredRange: num(r.preferredRange, 340),
      cooldown: num(r.cooldown, 2),
      damage: num(r.damage, 8),
      projectileSpeed: num(r.projectileSpeed, 320),
    };
    if (r.spread && num(r.spread.count, 0) > 1) {
      k.ranged.spread = { count: num(r.spread.count, 3), arc: num(r.spread.arc, 0.5) };
    }
  }
  if (e.melee) {
    const m = e.melee;
    k.melee = {
      approach: num(m.approach, 150),
      range: num(m.range, 140),
      halfArc: num(m.halfArc, 0.9),
      damage: num(m.damage, 12),
      hits: num(m.hits, 3),
      windup: num(m.windup, 0.5),
      swingGap: num(m.swingGap, 0.34),
      recover: num(m.recover, 0.95),
      step: num(m.step, 72),
    };
  }
  if (e.wieldsWeapon) k.wieldsWeapon = e.wieldsWeapon;
  if (e.dropWeapon != null) k.dropWeapon = num(e.dropWeapon, 0);
  if (shifter) k.shifter = { tier: num(e.shifterTier, 1), window: num(e.shifterWindow, 20) };
  return k;
}

const dimsData = JSON.parse(readFileSync(DIMS_SRC, "utf8"));
const shiftData = JSON.parse(readFileSync(SHIFT_SRC, "utf8"));

const dims = {};
const kinds = {};
let kindCount = 0;

for (const d of dimsData.dimensions) {
  const rosterEnemies = d.enemies.map((e) => e.id);
  dims[d.id] = {
    id: d.id,
    name: d.name,
    tagline: d.tagline,
    roster: [...rosterEnemies, d.tough.id],
    boss: d.boss.id,
    hazard: { name: d.hazard.name, description: d.hazard.description },
    palette: palette(d.palette),
    // Themed ground tile / POI / decal sets land with the art pass; until then the renderer falls back to
    // the shared Wild-West "tile-ground" + global decal/POI packs (palette re-skin does the heavy lifting).
    assets: { tile: "tile-ground", poiSet: d.id, decalSet: d.id },
  };
  for (const e of d.enemies) {
    kinds[e.id] = mapKind(e);
    kindCount++;
  }
  kinds[d.tough.id] = mapKind(d.tough);
  kinds[d.boss.id] = mapKind(d.boss, { boss: true });
  kindCount += 2;
}

for (const s of shiftData.shifters) {
  kinds[s.id] = mapKind(s, { shifter: true });
  kindCount++;
}

const banner =
  "// AUTO-GENERATED by tools/artkit/gen-dimensions.mjs — DO NOT EDIT.\n" +
  "// The §17 themed dimensions + their all-tier enemy rosters + the 3 cross-dimensional shifters, codegen'd\n" +
  "// from data/dimensions-design.json + data/dimension-shifters.json. shared/dimensions.ts merges\n" +
  "// EXTRA_DIMENSIONS into DIMENSIONS; shared/enemies.ts merges DIMENSION_ENEMY_KINDS into ENEMY_KINDS.\n" +
  "// Re-run the script after editing either data file. (Wild West stays hand-authored in those modules.)\n";
const body =
  `import type { DimensionDef } from "./dimensions.js";\n` +
  `import type { EnemyKind } from "./enemies.js";\n\n` +
  `export const EXTRA_DIMENSIONS: Record<string, DimensionDef> = ${JSON.stringify(dims, null, 2)};\n\n` +
  `export const DIMENSION_ENEMY_KINDS: Record<string, EnemyKind> = ${JSON.stringify(kinds, null, 2)};\n`;
// Unquote the palette colour sentinels ("0xrrggbb" → 0xrrggbb) so they read as real hex-number literals.
const text = `${banner}\n${body}`.replace(/"0x([0-9a-f]{6})"/g, "0x$1");
writeFileSync(OUT, text);

console.log(
  `wrote dimensions.generated.ts — ${Object.keys(dims).length} dimensions, ${kindCount} enemy kinds ` +
    `(${shiftData.shifters.length} shifters)`,
);
